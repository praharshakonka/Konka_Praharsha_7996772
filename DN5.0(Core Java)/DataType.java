class DataType {
    public static void main(String[]args)
    {
        int age=20;
        float weight=3.1f;
        char section='A';
        double salary=58349.5;
        boolean isStudent=true;
    System.out.println("Integer value : " + age);
    System.out.println("Float value : " + weight);
    System.out.println("Character value : " + section);
    System.out.println("Double value : " + salary);
    System.out.println("Boolean value : " + isStudent);
    }
}
